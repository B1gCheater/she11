#!/usr/bin/env python3
"""genconfig.py — regenerate src/shared/gen/config_gen.go from build inputs.
Used by builder.py and by the dev bootstrap."""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--role", required=True, choices=["client", "commander"])
    ap.add_argument("--server-cert", required=True)
    ap.add_argument("--magic", default="")
    ap.add_argument("--udp-servers", default="")
    ap.add_argument("--tcp-servers", default="")
    ap.add_argument("--ip-protocol", default="ipv4")
    ap.add_argument("--dns", default="")
    ap.add_argument("--doh", default="")
    ap.add_argument("--dns-allow-fallback", action="store_true")
    ap.add_argument("--dns-timeout", type=int, default=5)
    ap.add_argument("--handshake-timeout", type=int, default=5)
    ap.add_argument("--loop-delay", type=int, default=60)
    ap.add_argument("--delay-start", type=int, default=0)
    ap.add_argument("--max-shell", type=int, default=0)
    ap.add_argument("--mutex", default="")
    ap.add_argument("--out", default=str(ROOT / "src" / "shared" / "gen" / "config_gen.go"))
    args = ap.parse_args()

    cert = pathlib.Path(args.server_cert).read_text(encoding="utf-8")
    cert = cert.replace("\r\n", "\n").strip() + "\n"

    splits = lambda s: [x.strip() for x in s.split(",") if x.strip()] if s else []

    def goslice(lst):
        return "[]string{" + ", ".join(json.dumps(x) for x in lst) + "}"

    body = '''// Code generated by genconfig.py. DO NOT EDIT MANUALLY.

package gen

// Config holds build-time injected values.
var Config = ConfigData{{
\tServerCertPEM: {cert},
\tMagic:         {magic},
\tUDPServers:    {udp},
\tTCPServers:    {tcp},
\tIPProtocol:    {ipp},
\tDNS:           {dns},
\tDoH:           {doh},
\tDNSAllowFallback:  {daf},
\tDNSTimeoutSec:     {dnsT},
\tHandshakeTimeoutS: {hsT},
\tLoopDelaySec:      {ld},
\tDelayStartSec:     {ds},
\tMaxShell:          {ms},
\tMutexName:         {mutex},
}}
'''.format(
        cert=json.dumps(cert),
        magic=json.dumps(args.magic),
        udp=goslice(splits(args.udp_servers)),
        tcp=goslice(splits(args.tcp_servers)),
        ipp=json.dumps(args.ip_protocol),
        dns=goslice(splits(args.dns)),
        doh=goslice(splits(args.doh)),
        daf="true" if args.dns_allow_fallback else "false",
        dnsT=args.dns_timeout,
        hsT=args.handshake_timeout,
        ld=args.loop_delay,
        ds=args.delay_start,
        ms=args.max_shell,
        mutex=json.dumps(args.mutex),
    )
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    sys.exit(main())